let a = 20;
let b = 4;

console.log(a);
console.log(b);

// arithmetic operator

console.log("a + b is ", a + b);
console.log("a - b is ", a - b);
console.log("a - b is ", a * b);
console.log("a - b is ", a / b);
console.log("a % b is ", a % b);
console.log("a ** b is ", a ** b);
console.log("a++ is ", a++);
console.log("--b is ", --b);

// assignment operator
console.log("a+= is ", (a += 10));
console.log("a*=b is ", (a *= b));

